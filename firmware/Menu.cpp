void Menu::render(String label) {
      tft.fillScreen(bgColor);
      tft.setTextFont(1);
      tft.setTextColor(fontColor, fontColor);
      tft.drawString(FIRMWARE_VERSION, 118, 1); 
      tft.fillRoundRect(5 + currentInd * 40, 50, 30, 5, 2, TFT_WHITE);
      drawSVGKey_round(tft, 5, 20, TFT_WHITE);
      drawSVGRecents(tft, 36, 17);
      drawSVGCredit_card(tft, 80, 20);
      drawSVGNotepad_text(tft, 114, 20); 
      if (this->isBtMode) {
        tft.drawBitmap(130, 52, epd_bitmap_bluetooth_svgrepo_com__1_, 18, 18, fontColor);
        
      }else {
        
        tft.drawBitmap(130, 52, epd_bitmap_usb_193_svgrepo_com, 18, 18, fontColor);
      }
//      drawSVGRecent_svgrepo_com(tft, 0 ,10);
      tft.setTextFont(2);
      tft.setTextColor(fontColor, fontColor);
      if (this->locale == "ru" && currentInd == 0) {
        tft.drawBitmap(10, 62, epd_password_ru, 80, 15, fontColor);
        
      } else
      if (locale == "ru" && currentInd == 1) {
        tft.drawBitmap(10, 62, epd_recents_ru, 80, 15, fontColor);
        
      } else
      if (locale == "ru" && currentInd == 2) {
        tft.drawBitmap(10, 62, epd_cards_ru, 80, 15, fontColor);
        
      } else
      if (locale == "ru" && currentInd == 3) {
        tft.drawBitmap(10, 62, epd_notes_ru, 80, 15, fontColor);
        
      } else {
        tft.drawString(labels[currentInd].c_str(), 10, 62);  
      }
}

void Menu::setLabels(String labels[4]) {
  for (int i = 0; i < 4; ++i) {
    this->labels[i] = labels[i];
  }
}
void Menu::setLocale(String locale) {

    this->locale = locale;
}
void Menu::setIsBtMode(bool isBtMode) {

    this->isBtMode = isBtMode;
}
void Menu::setColor(uint16_t fontColor, uint16_t bgColor) {
  this->fontColor = fontColor;
  this->bgColor = bgColor;
}

int Menu::getCurrentInd() {
  return currentInd;
}

void Menu::next() {

  if (currentInd < 3) {
    currentInd += 1;
  } else {
    currentInd = 0;
  }

  this->render();
 
}

